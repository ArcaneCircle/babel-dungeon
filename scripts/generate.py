#!/usr/bin/env python3
import json
import os
import sys


def sort(sentences: dict[str, int]) -> list[int, str]:
    return sorted((s[1], s[0]) for s in sentences.items())


def sort0(pair: tuple[int, str]) -> int:
    words_count = len(pair[1].split())
    if words_count <= 2:
        return 1
    return words_count


def sort1(pair: tuple[int, str]) -> int:
    words_count = len(pair[1].split())
    if words_count <= 3:
        return 1
    return words_count


def sort2(pair: tuple[int, str]) -> int:
    words_count = len(pair[1].split())
    if words_count <= 5:
        return 1
    return words_count


def sort3(pair: tuple[int, str]) -> int:
    words_count = len(pair[1].split())
    if words_count <= 5:
        return 1
    if words_count <= 10:
        return 2
    return words_count


def process(source: str, sort_only: bool, start: int, count: int) -> list[str] | None:
    sentences: dict[str, int] = {}
    sentences_ids: set[int] = set()  # for counting duplicates
    sent2mean: dict[str, list[str]] = {}
    meanings: dict[str, int] = {}
    meanings_ids: set[int] = set()  # for counting duplicates
    with open(source) as fd:
        for line in fd.readlines():
            row = line.strip().split("\t")
            id = int(row[0])
            sentences_ids.add(id)
            sentence = row[1]
            if sentences.get(sentence, id + 1) > id:
                sentences[sentence] = id
            mlist = sent2mean.setdefault(sentence, [])
            meaning = row[3]
            if meaning not in mlist:
                mlist.append(meaning)
            mid = int(row[2])
            meanings_ids.add(mid)
            if meanings.get(meaning, mid + 1) > mid:
                meanings[meaning] = mid

    error = False
    print(f"{source}:")
    print(f"TOTAL SENTENCES: {len(sentences_ids)}")
    print(f"UNIQUE SENTENCES: {len(sentences)}")
    for sentence, id in sentences.items():
        if id not in sentences_ids:
            print(id, ":", sentence)
            error = True
        else:
            sentences_ids.remove(id)
    print("")
    print(f"TOTAL MEANINGS: {len(meanings_ids)}")
    print(f"UNIQUE MEANINGS: {len(meanings)}")
    for meaning, id in meanings.items():
        if id not in meanings_ids:
            print(id, ":", meaning)
            error = True
        else:
            meanings_ids.remove(id)
    print("")
    if error:
        print("ERROR")
        return None

    new_sents = []
    items = sorted(sort(sentences), key=sort0)
    for id, sen in list(items)[:100]:
        new_sents.append((id, sen))
        del sentences[sen]
    items = sorted(sort(sentences), key=sort1)
    for id, sen in list(items)[:500]:
        new_sents.append((id, sen))
        del sentences[sen]
    items = sorted(sort(sentences), key=sort2)
    for id, sen in list(items)[:10000]:
        new_sents.append((id, sen))
        del sentences[sen]
    items = sorted(sort(sentences), key=sort3)
    for id, sen in list(items):
        new_sents.append((id, sen))
        del sentences[sen]

    if sort_only:
        with open(source, "w") as f:
            for id, sen in new_sents:
                for meaning in sent2mean[sen]:
                    mid = meanings[meaning]
                    f.write(f"{id}\t{sen}\t{mid}\t{meaning}\n")
        print(f"sorted {len(new_sents)} sentences")
        return None

    return [f"{sen}\t{'|'.join(sent2mean[sen])}" for _, sen in new_sents[start:count]]


def write_constants(pairs: list[str]) -> None:
    CONSTANTS_FILE = "src/lib/constants.ts"
    langs: dict[str, list[str]] = {}
    for pair in pairs:
        lang1, lang2 = pair.split("-")
        langs.setdefault(lang1, []).append(lang2)
        langs.setdefault(lang2, []).append(lang1)
    with open(CONSTANTS_FILE, "w") as f:
        f.write("// AUTO-GENERATED by scripts/generate.py, do not edit\n")
        f.write(f"export const PAIRS: string[] = {json.dumps(pairs)};\n")
        f.write("// language to learn -> languages you can learn it from\n")
        f.write("export const LANGUAGES: Record<string, string[]> = {\n")
        for lang in sorted(langs):
            f.write(f"  {lang}: {json.dumps(sorted(langs[lang]))},\n")
        f.write("};\n")


def main() -> None:
    START = 0
    COUNT = 50000
    DATA_DIR = "public/data"
    sort_only = len(sys.argv) == 2 and sys.argv[1] == "sort"
    tsv_dir = "tsv"
    sources = sorted(each for each in os.listdir(tsv_dir) if each.endswith(".tsv"))
    if not sources:
        sys.exit("no .tsv files found")

    os.makedirs(DATA_DIR, exist_ok=True)
    pairs = []
    for source in sources:
        pair = source[: -len(".tsv")]
        if len(pair.split("-")) != 2:
            sys.exit(f"invalid file name {source}, expected <lang1>-<lang2>.tsv")
        print("")
        result = process(f'{tsv_dir}/{source}', sort_only, START, COUNT)
        if sort_only:
            continue
        if result is None:
            sys.exit(1)
        with open(f"{DATA_DIR}/{pair}.json", "w") as f:
            json.dump(result, f, ensure_ascii=False)
        pairs.append(pair)
        print(f"generated {len(result)} sentences for {pair}")

    if not sort_only:
        write_constants(pairs)


if __name__ == "__main__":
    main()
